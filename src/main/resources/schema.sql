CREATE TABLE IF NOT EXISTS ENTERPRISES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SYSTEM_NAME VARCHAR(255) NOT NULL,
    EXPORT_DATE TIMESTAMP,
    XML_DATA CLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS SUPPLIERS (
    SUPPLIER_ID VARCHAR(255) PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    RATING VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS COMPONENTS (
    COMPONENT_ID VARCHAR(255) PRIMARY KEY,
    SUPPLIER_REF VARCHAR(255) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    QUALITY_CLASS VARCHAR(50) NOT NULL,
    CONSTRAINT FK_COMPONENT_SUPPLIER
        FOREIGN KEY (SUPPLIER_REF) REFERENCES SUPPLIERS(SUPPLIER_ID)
);

CREATE TABLE IF NOT EXISTS STOCK (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ZONE VARCHAR(255) NOT NULL,
    COMPONENT_REF VARCHAR(255) NOT NULL,
    QUANTITY INTEGER NOT NULL,
    REORDER_LEVEL INTEGER NOT NULL,
    CONSTRAINT FK_STOCK_COMPONENT
        FOREIGN KEY (COMPONENT_REF) REFERENCES COMPONENTS(COMPONENT_ID)
);

CREATE TABLE IF NOT EXISTS VALUATIONS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPONENT_REF VARCHAR(255) NOT NULL,
    PRODUCTION_COST DECIMAL(19, 4) NOT NULL,
    PRODUCTION_CURRENCY VARCHAR(10) NOT NULL,
    RETAIL_PRICE DECIMAL(19, 4) NOT NULL,
    RETAIL_CURRENCY VARCHAR(10) NOT NULL,
    TAX_RATE DECIMAL(10, 6) NOT NULL,
    CONSTRAINT FK_VALUATION_COMPONENT
        FOREIGN KEY (COMPONENT_REF) REFERENCES COMPONENTS(COMPONENT_ID)
);